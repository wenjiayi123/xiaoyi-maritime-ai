const {chromium}=require('playwright');
const fs=require('node:fs/promises');
const path=require('node:path');
const assert=require('node:assert/strict');

(async()=>{
  const out=path.resolve(process.env.CROSSPORT_BROWSER_OUTPUT||'.codex_artifacts/crossport-20261030/browser-confirmed');
  await fs.mkdir(out,{recursive:true});
  const browser=await chromium.launch({headless:true,channel:'chrome'});
  const page=await browser.newPage({viewport:{width:1440,height:1080},acceptDownloads:true});
  const errors=[],checks=[];
  page.on('pageerror',e=>errors.push(e.message));
  try{
    const boot=page.waitForRequest(r=>r.url().endsWith('/api/port-simulator/stream'));
    await page.goto('http://127.0.0.1:8010',{waitUntil:'domcontentloaded'});
    await page.locator('#jointHarnessBtn').click();
    await page.locator('[data-cp="sources"]').click();
    await page.locator('[data-cp-source] h3').filter({hasText:'20456条'}).waitFor();
    assert.equal(await page.locator('[data-cp-source] tbody tr').count(),8);
    assert.match(await page.locator('[data-crossport-host]').innerText(),/并非无上下文零样本/);
    assert.match(await page.locator('[data-crossport-host]').innerText(),/缺少历史真实发布时间/);
    checks.push('eight-port source vintage, causal context and assumed release delay disclosed');
    await page.locator('[data-cp="diagnosis"]').click();
    await page.locator('[data-cp-diagnosis] h3').waitFor();
    assert.match(await page.locator('[data-cp-diagnosis]').innerText(),/探索性诊断/);
    assert.ok(await page.locator('[data-cp-diagnosis] tbody tr').count()>5);
    checks.push('legacy RL ablations visible with exploratory-test boundary');
    await page.locator('[data-cp="history"]').click();
    const study='hc-1aba62a9c3d9490f86f64c86151d7eef';
    await page.locator(`[data-cp="select"][data-id="${study}"]`).click();
    await page.locator('[data-cp-result] h3').filter({hasText:'已完成'}).waitFor();
    assert.match(await page.locator('[data-cp-result]').innerText(),/验证集选型：mpc/);
    assert.match(await page.locator('[data-cp-result]').innerText(),/未通过/);
    assert.match(await page.locator('[data-cp-physical]').innerText(),/未通过/);
    await page.locator('[data-cp-result] h3').first().scrollIntoViewIfNeeded();
    await page.screenshot({path:path.join(out,'crossport-holdout.png')});
    checks.push('persisted real five-seed study, MPC selection, CIs and failed research gates visible');
    assert.equal(await page.locator('[data-cp-feasibility] tbody tr').count(),4);
    assert.match(await page.locator('[data-cp-feasibility]').innerText(),/49/);
    checks.push('ex-post maximum-capacity infeasibility is separated from policy failure');
    await page.locator('[data-cp="adaptive"]').click();
    await page.locator('[data-cp-adaptive] h3').waitFor();
    assert.equal(await page.locator('[data-cp-adaptive] tbody tr').count(),27);
    assert.match(await page.locator('[data-cp-adaptive]').innerText(),/未通过：mae/);
    assert.match(await page.locator('[data-cp-adaptive]').innerText(),/不替代长期任务/);
    await page.locator('[data-cp-adaptive] h3').scrollIntoViewIfNeeded();
    await page.screenshot({path:path.join(out,'adaptive-twin-failures.png')});
    checks.push('fresh 2025 causal assimilation retains all 27 cells and adverse outcomes');
    await page.locator('[data-cp="readiness"]').click();
    await page.locator('[data-cp-readiness] h3').waitFor();
    assert.match(await page.locator('[data-cp-readiness]').innerText(),/完整验收未通过/);
    assert.equal(await page.locator('[data-cp-readiness] tbody tr').count(),11);
    assert.equal(await page.locator('[data-cp-readiness] a').count(),4);
    await page.locator('[data-cp-readiness] h3').scrollIntoViewIfNeeded();
    await page.screenshot({path:path.join(out,'leading-port-acceptance.png')});
    checks.push('leading-port gap matrix exposes unpassed gates and four primary references');
    const pending=page.waitForEvent('download');
    await page.locator('[data-cp="export"]').click();
    const saved=path.join(out,'ui-evidence.json');await(await pending).saveAs(saved);
    const receipt=JSON.parse(await fs.readFile(saved,'utf8'));
    assert.equal(receipt.report.job_id,study);
    assert.equal(receipt.catalog.entries.length,8);
    assert.equal(receipt.adaptive.results.filter(r=>r.research_gates_passed).length,17);
    assert.equal(receipt.readiness.top_port_full_acceptance,false);
    assert.equal(receipt.readiness.production_authority,false);
    checks.push('actual browser export preserves sources, assumptions, models, failures and disabled release');
    await page.setViewportSize({width:390,height:844});
    await page.locator('[data-cp-readiness] h3').scrollIntoViewIfNeeded();
    await page.screenshot({path:path.join(out,'mobile-acceptance.png')});
    const width=await page.locator('[data-crossport-host]').evaluate(el=>({width:el.getBoundingClientRect().width,viewport:innerWidth}));
    assert.ok(width.width<=width.viewport);
    checks.push('narrow viewport contains the workbench and scrollable evidence tables');
    await page.locator('#genericModal [data-action=close-modal]').click();
    await page.setViewportSize({width:1440,height:1080});
    await page.locator('#jointHarnessBtn').click();
    await page.locator('[data-cp-result] h3').filter({hasText:'已完成'}).waitFor();
    assert.match(await page.locator('[data-cp-result]').innerText(),new RegExp(study));
    checks.push('closing and reopening retains selected completed job and its evidence');
    assert.deepEqual(errors,[]);
    await fs.writeFile(path.join(out,'acceptance.json'),JSON.stringify({passed:true,checks,errors},null,2));
    console.log(JSON.stringify({passed:true,checks,errors}));
  }finally{await browser.close();}
})().catch(e=>{console.error(e);process.exit(1);});
