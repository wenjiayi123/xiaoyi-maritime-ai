/* Run with Playwright supplied by the documented workspace runtime. */
const {chromium} = require("playwright");
const fs = require("node:fs/promises");
const path = require("node:path");
const assert = require("node:assert/strict");

(async()=>{
  const base=process.env.HARNESS_TEST_URL || "http://127.0.0.1:18010";
  const out=path.resolve(process.env.HARNESS_TEST_OUTPUT || ".codex_artifacts/harness-20261028");
  await fs.mkdir(out,{recursive:true});
  const browser=await chromium.launch({headless:true,channel:"chrome"});
  const page=await browser.newPage({viewport:{width:1440,height:1050},acceptDownloads:true});
  const errors=[],checks=[];
  page.on("pageerror",e=>errors.push(e.message));
  try{
    await page.goto(base,{waitUntil:"domcontentloaded"});
    await page.locator("#harnessConsoleBtn").click();
    await page.locator("[data-hx-notice]").filter({hasText:"已登记"}).waitFor();
    checks.push("workbench opens and loads authenticated capabilities");
    await page.locator("[name=driver]").selectOption("rules");
    await page.locator("[name=goal]").fill("计算 (120+80)/4");
    await page.locator('[data-hx="create"]').click();
    await page.locator(".hx-task-heading strong").filter({hasText:"已完成"}).waitFor({timeout:20000});
    assert.match(await page.locator(".hx-final").innerText(),/50/);
    checks.push("real rule task runs, returns 50 and cites actual tool output");
    const downloadPromise=page.waitForEvent("download");
    await page.locator('[data-hx="export"]').click();
    await (await downloadPromise).saveAs(path.join(out,"browser-task-receipt.json"));
    const receipt=JSON.parse(await fs.readFile(path.join(out,"browser-task-receipt.json"),"utf8"));
    assert.equal(receipt.integrity.event_chain_valid,true);
    checks.push("downloaded receipt has a valid event chain");
    await page.locator('.hx-details summary').filter({hasText:"我的偏好记忆"}).click();
    await page.locator('[name="memoryText"]').fill("浏览器验收临时偏好：保留单位");
    await page.locator('[data-hx="memory-save"]').click();
    await page.locator(".hx-memory").filter({hasText:"浏览器验收临时偏好"}).waitFor();
    await page.locator(".hx-memory").filter({hasText:"浏览器验收临时偏好"}).getByRole("button",{name:"删除"}).click();
    await page.waitForFunction(()=>!document.querySelector("[data-hx-memory]").textContent.includes("浏览器验收临时偏好"));
    checks.push("explicit memory can be saved and deleted");
    await page.locator('[name="goal"]').fill("保留未提交的任务草稿");
    await page.locator('#genericModal [data-action="close-modal"]').click();
    await page.locator("#harnessConsoleBtn").click();
    await page.locator("[data-hx-notice]").filter({hasText:"已登记"}).waitFor();
    assert.equal(await page.locator('[name="goal"]').inputValue(),"保留未提交的任务草稿");
    await page.locator(".hx-task-heading strong").filter({hasText:"已完成"}).waitFor();
    checks.push("reopen preserves task and unsent goal draft");
    await page.screenshot({path:path.join(out,"workbench-desktop.png"),fullPage:true});
    await page.setViewportSize({width:390,height:844});
    await page.waitForTimeout(250);
    const overflow=await page.locator("#harnessConsole").evaluate(el=>({scroll:el.scrollWidth,client:el.clientWidth}));
    assert.ok(overflow.scroll<=overflow.client+1,JSON.stringify(overflow));
    await page.screenshot({path:path.join(out,"workbench-mobile.png"),fullPage:true});
    checks.push("390px layout has no horizontal overflow");
    await page.setViewportSize({width:1440,height:1050});
    await page.locator('[name="goal"]').fill("分析这个港口的岸电SOP");
    await page.locator('[data-hx="create"]').click();
    await page.locator(".hx-task-heading strong").filter({hasText:"等待补充信息"}).waitFor({timeout:20000});
    await page.locator('[name="steer"]').fill("港口是洛杉矶港，分析公开资料即可，不要求现场数据。");
    await page.locator('[data-hx="input"]').click();
    await page.locator(".hx-task-heading strong").filter({hasText:"已完成"}).waitFor({timeout:20000});
    checks.push("clarification answer resumes the same task to completion");
    if(process.env.HARNESS_TEST_MARITIME==="1"){
      const before=await (await page.request.get(`${base}/api/port-simulator/status`)).json();
      await page.locator('[name="template"]').selectOption("port-briefing");
      assert.match(await page.locator('[name="goal"]').inputValue(),/港航联合研判/);
      const previousTask=(await page.locator(".hx-task-heading small").filter({hasText:/ht-/}).innerText()).match(/ht-[a-f0-9]+/)[0];
      await page.locator('[data-hx="create"]').click();
      await page.waitForFunction(previous=>{const heading=document.querySelector('.hx-task-heading')?.textContent||"";return /ht-/.test(heading)&&!heading.includes(previous);},previousTask);
      await page.locator(".hx-task-heading strong").filter({hasText:"已完成"}).waitFor({timeout:30000});
      assert.match(await page.locator(".hx-final").innerText(),/港航交接简报/);
      checks.push("port briefing template executes five real tools and delivers a handover draft");
      const comparison=page.locator('.hx-results details').filter({hasText:"twin.compare"});
      await comparison.locator('summary').click();
      await comparison.getByRole('button',{name:"查看完整工具结果"}).click();
      await page.locator('[data-hx-artifact] table').waitFor();
      assert.match(await page.locator('[data-hx-artifact]').innerText(),/电网需量 kW/);
      assert.equal(await page.locator('[data-hx-artifact] tbody tr').count(),3);
      await page.locator('[data-hx-artifact]').scrollIntoViewIfNeeded();
      await page.screenshot({path:path.join(out,"maritime-comparison-desktop.png"),fullPage:true});
      checks.push("scenario result displays units, baseline deltas and explicit engineering assumptions");
      await page.setViewportSize({width:390,height:844});
      const overflow=await page.locator("#harnessConsole").evaluate(el=>({scroll:el.scrollWidth,client:el.clientWidth}));
      assert.ok(overflow.scroll<=overflow.client+1,JSON.stringify(overflow));
      await page.locator('[data-hx-artifact]').scrollIntoViewIfNeeded();
      await page.screenshot({path:path.join(out,"maritime-comparison-mobile.png"),fullPage:true});
      await page.setViewportSize({width:1440,height:1050});
      checks.push("wide comparison table scrolls within the 390px workbench");
      const handover=page.locator('.hx-results details').filter({has:page.locator('summary').filter({hasText:"maritime.handover"})});
      await handover.locator('summary').click();
      await handover.getByRole('button',{name:"查看完整工具结果"}).click();
      await page.locator('[data-hx-artifact]').filter({hasText:"待责任人、截止时间与接收人签收"}).waitFor();
      assert.match(await page.locator('[data-hx-artifact]').innerText(),/待责任人、截止时间与接收人签收/);
      const taskId=(await page.locator(".hx-task-heading small").filter({hasText:/ht-/}).innerText()).match(/ht-[a-f0-9]+/)[0];
      const receipt=await (await page.request.get(`${base}/api/harness/tasks/${taskId}/export`)).json();
      assert.equal(receipt.integrity.event_chain_valid,true);
      const reports=receipt.artifacts.filter(a=>/^T[2-5]\.json$/.test(a.name)).map(a=>JSON.parse(a.content));
      assert.equal(new Set(reports.map(r=>r.snapshot_sha256)).size,1);
      assert.equal(reports.find(r=>r.handover_state).readiness.operational_release,false);
      await fs.writeFile(path.join(out,"maritime-browser-receipt.json"),JSON.stringify(receipt,null,2));
      const after=await (await page.request.get(`${base}/api/port-simulator/status`)).json();
      assert.equal(after.run_id,before.run_id);assert.equal(after.scenario_id,before.scenario_id);
      checks.push("all business artifacts share one baseline and leave current simulator configuration intact");
      await page.locator('[name="template"]').selectOption("");
    }
    if(process.env.HARNESS_TEST_LINKED==="1"){
      await page.locator('[name="goal"]').fill("马六甲切换集中到港并观测");
      await page.locator('[data-hx="create"]').click();
      await page.locator(".hx-task-heading strong").filter({hasText:"等待操作审批"}).waitFor({timeout:20000});
      await page.locator('[data-hx="reject"]').click();
      await page.locator(".hx-task-heading strong").filter({hasText:"已阻止"}).waitFor();
      checks.push("real simulation approval can be rejected without execution");
      await page.locator('[data-hx="create"]').click();
      await page.locator(".hx-task-heading strong").filter({hasText:"等待操作审批"}).waitFor({timeout:20000});
      await page.locator('.hx-approval').scrollIntoViewIfNeeded();
      await page.screenshot({path:path.join(out,"workbench-approval.png"),fullPage:true});
      await page.locator('[data-hx="approve"]').click();
      await page.locator(".hx-task-heading strong").filter({hasText:"已完成"}).waitFor({timeout:25000});
      const taskId=(await page.locator(".hx-task-heading small").filter({hasText:/ht-/}).innerText()).match(/ht-[a-f0-9]+/)[0];
      const response=await page.request.get(`${base}/api/harness/tasks/${taskId}/export`);
      const data=await response.json();
      const target=JSON.parse(data.artifacts.find(a=>a.name==="T1.json").content);
      assert.equal(target.receipt.restored,true);
      await fs.writeFile(path.join(out,"browser-approved-receipt.json"),JSON.stringify(data,null,2));
      checks.push("real simulation executes after approval and verifies configuration restoration");
    }
    await page.locator('#genericModal [data-action="close-modal"]').click();
    let release;
    const gate=new Promise(resolve=>release=resolve);
    await page.route("**/api/harness/capabilities",async route=>{await gate;await route.fulfill({status:503,contentType:"application/json",body:'{"detail":"isolated delayed failure"}'});});
    await page.locator("#harnessConsoleBtn").click();
    await page.locator('#genericModal [data-action="close-modal"]').click();
    await page.locator('[data-action="settings"]').first().click();
    release();await page.waitForTimeout(300);
    assert.notEqual(await page.locator("#modalTitle").innerText(),"Harness 任务工作台");
    assert.ok(!(await page.locator("#modalBody").innerText()).includes("isolated delayed failure"));
    checks.push("late workbench failure cannot overwrite another dialog");
    assert.deepEqual(errors,[]);
    await fs.writeFile(path.join(out,"browser-acceptance.json"),JSON.stringify({passed:true,checks,pageErrors:errors},null,2));
    console.log(JSON.stringify({passed:true,checks},null,2));
  }finally{await browser.close();}
})().catch(error=>{console.error(error);process.exitCode=1;});
