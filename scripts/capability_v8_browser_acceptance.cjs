const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
const assert = require('node:assert/strict');
const fs = require('node:fs/promises');
const path = require('node:path');

(async () => {
  const out = path.resolve('.codex_artifacts/capability-review-v8-20261031/browser');
  await fs.mkdir(out, { recursive: true });
  const browser = await chromium.launch({ headless: true, channel: 'chrome' });
  const page = await browser.newPage({ viewport: { width: 1440, height: 1050 }, acceptDownloads: true });
  const checks = [], errors = [], receipts = [];
  page.on('pageerror', error => errors.push(error.message));
  try {
    await page.goto('http://127.0.0.1:18018/', { waitUntil: 'domcontentloaded' });
    await page.locator('a.capability-review-link').click();
    await page.waitForURL('**/web/capability-review.html');
    await page.getByText('证据与本轮源码一致。', { exact: false }).waitFor();
    assert.equal(await page.locator('[data-component]').count(), 37);
    checks.push('main app navigation opens the current registered 37-item review');
    await page.locator('[data-component=forecast] summary').click();
    assert.match(await page.locator('[data-component=forecast]').innerText(), /26达到覆盖门槛/);
    assert.match(await page.locator('[data-component=forecast]').innerText(), /65/);
    await page.locator('#search').fill('泊位');
    assert.ok(await page.locator('[data-component=schedule]').count());
    await page.locator('#search').fill('');
    await page.locator('#priority').selectOption('P0');
    assert.ok((await page.locator('[data-component]').count()) < 37);
    await page.locator('#priority').selectOption('');
    checks.push('37 scores, dimensions, current limitations, priority filter and concrete acceptance conditions');
    await page.screenshot({ path: path.join(out, 'overview-desktop.png'), fullPage: false });
    async function run(button, endpoint) {
      const pending = page.waitForResponse(r => r.url().endsWith(endpoint) && r.request().method() === 'POST');
      await page.locator(button).click();
      const response = await pending;
      assert.equal(response.status(), 200);
      const body = await response.json();
      assert.equal(body.production_authority, false);
      assert.ok(body.result_sha256);
      receipts.push(body);
      await page.waitForFunction(selector => !document.querySelector(selector).disabled, button);
      return body;
    }
    const first = await run('#run-forecast', '/forecast');
    assert.equal(first.publication_cutoff, '2026-05-25');
    assert.equal(first.target, '2026-06-08');
    await page.locator('#fault').selectOption('source_gap');
    const missing = await run('#run-forecast', '/forecast');
    assert.equal(missing.status, 'hold');
    assert.equal(missing.prediction, null);
    assert.match(await page.locator('#forecast-result').innerText(), /暂停/);
    await page.locator('#fault').selectOption('demand_shift');
    const shifted = await run('#run-forecast', '/forecast');
    assert.equal(shifted.status, 'hold');
    assert.ok(shifted.reasons.includes('observed_demand_shift'));
    await page.locator('#fault').selectOption('none');
    await page.locator('#port').selectOption('port777');
    await page.locator('#horizon').selectOption('14');
    const changed = await run('#run-forecast', '/forecast');
    assert.equal(changed.horizon_days, 14);
    assert.equal(changed.target, '2026-06-15');
    assert.notEqual(changed.input_sha256, first.input_sha256);
    assert.equal(await page.locator('#forecast-cells tr').count(), 2);
    checks.push('actual forecast recomputation, publication cutoff, missing-source hold, shift hold and different port/horizon');
    const schedule = await run('#run-schedule', '/schedule');
    assert.equal(schedule.robust.scenarios.length, 5);
    assert.equal(schedule.robust_failed_scenarios, 0);
    assert.ok(schedule.nominal_failed_scenarios > 0);
    assert.equal(await page.locator('#schedule-result svg rect').count(), schedule.nominal.schedule.length + schedule.robust.schedule.length);
    assert.match(await page.locator('#schedule-result').innerText(), /代理成本增加/);
    await page.locator('#schedule-result').scrollIntoViewIfNeeded();
    await page.screenshot({ path: path.join(out, 'robust-plan-desktop.png'), fullPage: false });
    checks.push('actual five-scenario shared plan, honest cost increase, all feasibility checks and visible Gantt');
    await page.locator('#grid').fill('1200');
    const constrained = await run('#run-schedule', '/schedule');
    assert.equal(constrained.robust_failed_scenarios, 0);
    assert.ok(constrained.robust.scenarios[0].deferred_calls > 0);
    assert.match(await page.locator('#schedule-result').innerText(), /暂缓/);
    checks.push('capacity reduction changes plan and exposes deferred work rather than false completion');
    const downloadPromise = page.waitForEvent('download');
    await page.locator('#export').click();
    const download = await downloadPromise;
    const destination = path.join(out, 'review-export.json');
    await download.saveAs(destination);
    const exported = JSON.parse(await fs.readFile(destination, 'utf8'));
    assert.equal(exported.catalog.scorecard.components.length, 37);
    assert.equal(exported.session_receipts.length, receipts.length);
    assert.equal(exported.catalog.results.forecast_predictions, 1872);
    assert.equal(exported.production_authority, false);
    checks.push('download contains all 37 assessments, known failures and only the actual session receipts');
    await page.setViewportSize({ width: 390, height: 844 });
    await page.evaluate(() => window.scrollTo(0, 0));
    await page.screenshot({ path: path.join(out, 'overview-mobile.png'), fullPage: false });
    assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth + 1));
    await page.locator('#search').fill('预测');
    assert.ok(await page.locator('[data-component]').count());
    checks.push('390px viewport remains usable without page overflow');
    assert.deepEqual(errors, []);
    checks.push('no browser JavaScript runtime errors');
    await fs.writeFile(path.join(out, 'acceptance.json'), JSON.stringify({ passed: true, checks, errors, receipts: receipts.map(r => r.result_sha256), production_authority: false }, null, 2));
    console.log(JSON.stringify({ passed: true, checks }, null, 2));
  } finally {
    await browser.close();
  }
})().catch(error => { console.error(error); process.exitCode = 1; });
