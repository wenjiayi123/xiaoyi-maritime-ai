const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
const assert = require('node:assert/strict');
const fs = require('node:fs/promises');
const path = require('node:path');
const crypto = require('node:crypto');

(async () => {
  const out = path.resolve('.codex_artifacts/root-cause-v10-20261031/browser');
  await fs.mkdir(out, { recursive: true });
  const browser = await chromium.launch({ headless: true, channel: 'chrome' });
  const page = await browser.newPage({ viewport: { width: 1440, height: 1050 }, acceptDownloads: true });
  const checks = [], errors = [], receipts = [];
  page.on('pageerror', error => errors.push(error.message));
  try {
    await page.goto('http://127.0.0.1:18018/', { waitUntil: 'domcontentloaded' });
    await page.locator('a.root-cause-v10-link').click();
    await page.waitForURL('**/web/root-cause-v10.html');
    await page.getByText('冻结证据与当前实现一致', { exact: false }).waitFor();
    assert.equal(await page.locator('#components tr').count(), 37);
    assert.equal(await page.locator('#metrics article').count(), 2);
    assert.match(await page.locator('#metrics').innerText(), /45 → 50/);
    assert.match(await page.locator('#metrics').innerText(), /30 → 30/);
    checks.push('main navigation, two evidence-bound scores and all 37 limitation assessments');
    assert.equal(await page.locator('#oracle tr').count(), 4);
    assert.match(await page.locator('#oracle').innerText(), /15\/16/);
    assert.match(await page.locator('#rl-result').innerText(), /未通过/);
    assert.equal(await page.locator('#annual-summary tr').count(), 2);
    assert.match(await page.locator('#annual-summary').innerText(), /25\/32/);
    assert.equal(await page.locator('#annual-sites tr').count(), 8);
    checks.push('oracle future-information boundary, rejected RL admission and all eight annual sites');
    await page.screenshot({ path: path.join(out, 'overview-desktop.png'), fullPage: false });
    async function run(station) {
      await page.locator('#station').selectOption(station);
      const pending = page.waitForResponse(r => r.url().endsWith('/root-cause-v10/annual') && r.request().method() === 'POST');
      await page.locator('#run').click();
      const response = await pending;
      assert.equal(response.status(), 200);
      const body = await response.json();
      assert.equal(body.production_authority, false);
      receipts.push(body);
      await page.waitForFunction(() => !document.querySelector('#run').disabled);
      return body;
    }
    const missing = await run('8775870');
    assert.equal(missing.status, 'hold');
    assert.ok(!missing.rows);
    assert.match(await page.locator('#annual-receipt').innerText(), /不补造预测/);
    const catalog = await (await page.request.get('http://127.0.0.1:18018/api/harness/root-cause-v10/catalog')).json();
    const failed = catalog.summary.annual.cells.find(c => c.method === 'v10_selected' && c.annual.mae_m != null && (!c.annual.passed || Object.values(c.quarters).some(q => !q.passed)));
    assert.ok(failed);
    const held = await run(failed.station_id);
    assert.equal(held.status, 'hold');
    assert.equal(held.rows.length, 24);
    assert.match(await page.locator('#annual-receipt').innerText(), /暂停研究使用/);
    checks.push('missing history and observed scientific failures remain on hold');
    const annual = await run('9444900');
    assert.equal(annual.rows.length, 24);
    assert.equal(annual.status, 'research_only');
    assert.equal(annual.language_model_used, false);
    assert.equal(annual.datum, 'MLLW');
    assert.ok(annual.rows.every(r => !('actual' in r) && r.upper90 - r.lower90 <= r.v9_upper90 - r.v9_lower90 + 1e-10));
    assert.equal(await page.locator('#annual-receipt svg polygon').count(), 2);
    assert.equal(await page.locator('#annual-receipt svg polyline').count(), 1);
    assert.equal(await page.locator('#annual-receipt details').count(), 1);
    checks.push('actual 24-hour reconstruction, identical point prediction and old/new interval chart');
    await page.locator('#annual-receipt').scrollIntoViewIfNeeded();
    await page.screenshot({ path: path.join(out, 'annual-desktop.png'), fullPage: false });
    const waiting = page.waitForEvent('download');
    await page.locator('#export').click();
    const download = await waiting;
    const file = path.join(out, 'evidence-export.json');
    await download.saveAs(file);
    const exported = JSON.parse(await fs.readFile(file, 'utf8'));
    assert.equal(exported.catalog.scorecard.components.length, 37);
    assert.equal(exported.catalog.summary.all_scientific_limits_resolved, false);
    assert.equal(exported.catalog.summary.all_37_capabilities_causally_tested, false);
    assert.equal(exported.receipt.result_sha256, annual.result_sha256);
    checks.push('export contains actual receipt, complete assessments and unresolved limitations');
    await page.locator('#day').fill('2026-01-01');
    const invalid = page.waitForResponse(r => r.url().endsWith('/root-cause-v10/annual') && r.request().method() === 'POST');
    await page.locator('#run').click();
    assert.equal((await invalid).status(), 422);
    await page.getByText('未完成：请选择本次独立测试', { exact: false }).waitFor();
    checks.push('out-of-scope year rejected by actual API and visibly reported');
    await page.setViewportSize({ width: 390, height: 844 });
    await page.evaluate(() => window.scrollTo(0, 0));
    await page.screenshot({ path: path.join(out, 'overview-mobile.png'), fullPage: false });
    assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1));
    checks.push('390px viewport has no page overflow');
    await page.goto('http://127.0.0.1:18018/web/priority-v9.html');
    await page.getByText('证据摘要与当前代码一致', { exact: false }).waitFor();
    assert.equal(await page.locator('#score-rows tr').count(), 37);
    checks.push('V9 review remains current and separately accessible');
    assert.deepEqual(errors, []);
    checks.push('no browser JavaScript exceptions');
    const source_sha256 = {};
    for (const file of ['web/root-cause-v10.html', 'web/root-cause-v10.js', 'web/capability-review.css', 'scripts/root_cause_v10_browser_acceptance.cjs']) source_sha256[file] = crypto.createHash('sha256').update(await fs.readFile(file)).digest('hex');
    await fs.writeFile(path.join(out, 'acceptance.json'), JSON.stringify({ passed: true, checks, errors, receipts, source_sha256, production_authority: false }, null, 2));
    console.log(JSON.stringify({ passed: true, checks }, null, 2));
  } finally { await browser.close(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
