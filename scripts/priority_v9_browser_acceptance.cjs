const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
const assert = require('node:assert/strict');
const fs = require('node:fs/promises');
const path = require('node:path');
const crypto = require('node:crypto');

(async () => {
  const out = path.resolve('.codex_artifacts/priority-v9-20261031/browser');
  await fs.mkdir(out, { recursive: true });
  const browser = await chromium.launch({ headless: true, channel: 'chrome' });
  const page = await browser.newPage({ viewport: { width: 1440, height: 1050 }, acceptDownloads: true });
  const checks = [], errors = [], receipts = [];
  page.on('pageerror', error => errors.push(error.message));
  try {
    await page.goto('http://127.0.0.1:18018/', { waitUntil: 'domcontentloaded' });
    await page.locator('a.priority-v9-link').click();
    await page.waitForURL('**/web/priority-v9.html');
    await page.getByText('证据摘要与当前代码一致', { exact: false }).waitFor();
    assert.equal(await page.locator('#score-rows tr').count(), 37);
    assert.equal(await page.locator('#metrics article').count(), 3);
    assert.match(await page.locator('#metrics').innerText(), /65 → 70/);
    assert.match(await page.locator('#metrics').innerText(), /30 → 30/);
    checks.push('main navigation, three evidence-bound scores and all 37 current assessments');
    assert.equal(await page.locator('#forecast-methods tr').count(), 3);
    assert.match(await page.locator('#forecast-methods').innerText(), /21\/21/);
    assert.match(await page.locator('#rl-verdict').innerText(), /未通过/);
    assert.equal(await page.locator('#annual-cells tr').count(), 8);
    checks.push('simple forecast baseline, failed RL admission and all eight annual sites remain visible');
    await page.screenshot({ path: path.join(out, 'overview-desktop.png'), fullPage: false });
    async function run(kind) {
      const pending = page.waitForResponse(r => r.url().endsWith(`/priority-v9/${kind}`) && r.request().method() === 'POST');
      await page.locator(`#run-${kind}`).click();
      const response = await pending;
      assert.equal(response.status(), 200);
      const body = await response.json();
      assert.equal(body.production_authority, false);
      receipts.push(body);
      await page.waitForFunction(k => !document.querySelector(`#run-${k}`).disabled, kind);
      return body;
    }
    const first = await run('forecast');
    assert.equal(first.publication_cutoff, '2026-05-25');
    assert.equal(first.target, '2026-06-08');
    assert.ok(!('actual' in first));
    await page.locator('#fault').selectOption('source_gap');
    const missing = await run('forecast');
    assert.equal(missing.status, 'hold');
    assert.equal(missing.prediction, null);
    await page.locator('#fault').selectOption('none');
    await page.locator('#port').selectOption('port141');
    await page.locator('#horizon').selectOption('14');
    const changed = await run('forecast');
    assert.equal(changed.target, '2026-06-15');
    assert.notEqual(changed.result_sha256, first.result_sha256);
    checks.push('actual causal forecast, missing-source hold and changed port/horizon; future truth absent');
    await page.locator('#station').selectOption('9414290');
    const blocked = await run('annual');
    assert.equal(blocked.status, 'hold');
    assert.ok(!blocked.rows);
    await page.locator('#station').selectOption('8724580');
    const quarterFail = await run('annual');
    assert.equal(quarterFail.annual_checks.passed, true);
    assert.equal(quarterFail.quarter_checks['4'].passed, false);
    assert.equal(quarterFail.status, 'hold');
    await page.locator('#station').selectOption('8771450');
    const annual = await run('annual');
    assert.equal(annual.rows.length, 24);
    assert.equal(annual.status, 'research_only');
    assert.equal(annual.datum, 'MLLW');
    assert.equal(await page.locator('#annual-result svg polygon').count(), 1);
    assert.equal(await page.locator('#annual-result svg polyline').count(), 1);
    assert.equal(await page.locator('#annual-result details').count(), 1);
    assert.match(await page.locator('#annual-result').innerText(), /四个季度均通过/);
    checks.push('blocked history, failed quarter despite passing annual mean, and actual 24-hour harmonic reconstruction');
    await page.locator('#annual').scrollIntoViewIfNeeded();
    await page.screenshot({ path: path.join(out, 'annual-desktop.png'), fullPage: false });
    const waiting = page.waitForEvent('download');
    await page.locator('#export').click();
    const download = await waiting;
    const file = path.join(out, 'evidence-export.json');
    await download.saveAs(file);
    const exported = JSON.parse(await fs.readFile(file, 'utf8'));
    assert.equal(exported.catalog.scorecard.components.length, 37);
    assert.equal(exported.catalog.summary.all_three_limitations_resolved, false);
    assert.equal(exported.receipts.annual.result_sha256, annual.result_sha256);
    checks.push('export contains actual receipts, complete scorecard and unresolved limitations');
    await page.setViewportSize({ width: 390, height: 844 });
    await page.evaluate(() => window.scrollTo(0, 0));
    await page.screenshot({ path: path.join(out, 'overview-mobile.png'), fullPage: false });
    assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1));
    checks.push('390px viewport has no page overflow');
    assert.deepEqual(errors, []);
    checks.push('no browser JavaScript exceptions');
    // Existing review remains accessible and still bound to its unchanged V8 evidence.
    await page.goto('http://127.0.0.1:18018/web/capability-review.html');
    await page.getByText('证据与本轮源码一致。', { exact: false }).waitFor();
    assert.equal(await page.locator('[data-component]').count(), 37);
    checks.push('V8 review remains current and separately accessible');
    const source_sha256 = {};
    for (const file of ['web/priority-v9.html', 'web/priority-v9.js', 'web/capability-review.css', 'scripts/priority_v9_browser_acceptance.cjs']) source_sha256[file] = crypto.createHash('sha256').update(await fs.readFile(file)).digest('hex');
    await fs.writeFile(path.join(out, 'acceptance.json'), JSON.stringify({ passed: true, checks, errors, receipts, source_sha256, production_authority: false }, null, 2));
    console.log(JSON.stringify({ passed: true, checks }, null, 2));
  } finally { await browser.close(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
