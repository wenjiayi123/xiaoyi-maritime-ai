const {chromium}=require('playwright');
const fs=require('node:fs/promises');
const path=require('node:path');
const assert=require('node:assert/strict');

(async()=>{
  const out=path.resolve('.codex_artifacts/remediation-v3-20261030/browser');
  await fs.mkdir(out,{recursive:true});
  const browser=await chromium.launch({headless:true,channel:'chrome'});
  const page=await browser.newPage({viewport:{width:1440,height:1080},acceptDownloads:true});
  const errors=[],checks=[];
  page.on('pageerror',e=>errors.push(e.message));
  try{
    const boot=page.waitForRequest(r=>r.url().endsWith('/api/port-simulator/stream'));
    await page.goto('http://127.0.0.1:8010',{waitUntil:'domcontentloaded'});
    await boot;
    await page.locator('#jointHarnessBtn').click();
    const reply=page.waitForResponse(r=>r.url().endsWith('/api/harness/assurance/remediation-v3'));
    await page.locator('[data-cp=learning]').click();
    assert.equal((await reply).status(),200);
    const host=page.locator('[data-cp-learning]');
    await host.locator('h3').filter({hasText:'六项续改'}).waitFor();
    assert.match(await host.innerText(),/当前证据已核验/);
    assert.equal(await host.locator('table').nth(0).locator('tbody tr').count(),7);
    assert.match(await host.innerText(),/只关闭TD/);
    assert.match(await host.innerText(),/只模仿不计作RL/);
    checks.push('seven paired ablations and computational-replicate limitations are visible');
    assert.equal(await host.locator('table').nth(1).locator('tbody tr').count(),14);
    assert.equal(await host.locator('table').nth(2).locator('tbody tr').count(),8);
    assert.match(await host.innerText(),/2\.7030%/);
    assert.match(await host.innerText(),/研究准入：未通过/);
    assert.match(await host.innerText(),/没有在线MPC回退/);
    checks.push('mean RL gain is shown with failed interval, per-port and safety gates');
    assert.equal(await host.locator('table').nth(3).locator('tbody tr').count(),8);
    assert.match(await host.innerText(),/Santos/);
    assert.match(await host.innerText(),/同一已固定IMF导出/);
    assert.equal(await host.locator('table').nth(4).locator('tbody tr').count(),8);
    checks.push('unseen whole-port provenance and supplementary frozen forecast checks are explicit');
    assert.equal(await host.locator('table').nth(5).locator('tbody tr').count(),75);
    assert.match(await host.innerText(),/长期 5\/21/);
    assert.match(await host.innerText(),/短期 46\/54/);
    assert.match(await host.innerText(),/no_evaluable_observations/);
    await host.locator('h3').filter({hasText:'孪生新时期'}).scrollIntoViewIfNeeded();
    await page.screenshot({path:path.join(out,'new-tide-failures.png')});
    checks.push('all75 new physical cells retain long-horizon regressions and missing observations');
    assert.equal(await host.locator('table').nth(6).locator('tbody tr').count(),32);
    assert.match(await host.innerText(),/外部一致性认证：未完成/);
    assert.match(await host.innerText(),/工程假设/);
    checks.push('joint resource and energy cases and PC2 subset limits remain clear');
    assert.match(await host.locator('h3').filter({hasText:'Docker实际构建'}).innerText(),/当前版本通过/);
    checks.push('actual current Docker receipt is displayed with deployment boundary');
    await page.locator('[data-cp=history]').click();
    await page.locator('[data-cp=select][data-id="hc-1aba62a9c3d9490f86f64c86151d7eef"]').click();
    await page.locator('[data-cp-result] h3').filter({hasText:'已完成'}).waitFor();
    await page.locator('[data-cp=readiness]').click();
    const matrix=page.locator('[data-cp-readiness]');
    await matrix.locator('h3').waitFor();
    assert.match(await matrix.innerText(),/5 \/ 11/);
    assert.match(await matrix.innerText(),/完整验收未通过/);
    checks.push('complete11-criterion assessment still reports six unpassed criteria');
    const download=page.waitForEvent('download');
    await page.locator('[data-cp=export]').click();
    const filename=path.join(out,'ui-evidence.json');await(await download).saveAs(filename);
    const data=JSON.parse(await fs.readFile(filename,'utf8'));
    assert.equal(data.learning.current,true);
    assert.equal(data.learning.learning.runs.length,1664);
    assert.equal(data.learning.physical.results.length,75);
    assert.equal(data.learning.docker.current,true);
    assert.equal(data.readiness.passed_items,5);
    assert.equal(data.learning.production_authority,false);
    checks.push('real UI export includes protocols, failures, Docker, independent readback and matrix');
    await page.setViewportSize({width:390,height:844});
    await host.locator('h3').first().scrollIntoViewIfNeeded();
    const widths=await host.evaluate(el=>({width:el.getBoundingClientRect().width,viewport:innerWidth}));
    assert.ok(widths.width<=widths.viewport);
    await page.screenshot({path:path.join(out,'mobile-learning.png')});
    assert.deepEqual(errors,[]);
    checks.push('new evidence remains contained on narrow viewports without script errors');
    await fs.writeFile(path.join(out,'acceptance.json'),JSON.stringify({passed:true,checks,errors},null,2));
    console.log(JSON.stringify({passed:true,checks,errors}));
  }finally{await browser.close();}
})().catch(e=>{console.error(e);process.exit(1);});
