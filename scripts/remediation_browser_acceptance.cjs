const {chromium}=require('playwright');
const fs=require('node:fs/promises');
const path=require('node:path');
const assert=require('node:assert/strict');

(async()=>{
  const out=path.resolve('.codex_artifacts/remediation-20261030/browser');
  await fs.mkdir(out,{recursive:true});
  const browser=await chromium.launch({headless:true,channel:'chrome'});
  const page=await browser.newPage({viewport:{width:1440,height:1080},acceptDownloads:true});
  const errors=[],checks=[];
  page.on('pageerror',e=>errors.push(e.message));
  try{
    const boot=page.waitForRequest(r=>r.url().endsWith('/api/port-simulator/stream'));
    await page.goto('http://127.0.0.1:8010',{waitUntil:'domcontentloaded'});
    await boot;
    await page.locator('#jointHarnessBtn').click();
    const response=page.waitForResponse(r=>r.url().endsWith('/api/harness/assurance/remediation-v2'));
    await page.locator('[data-cp=remediation]').click();
    assert.equal((await response).status(),200);
    const host=page.locator('[data-cp-remediation]');
    await host.locator('h3').filter({hasText:'剩余八项整改'}).waitFor();
    assert.equal(await host.locator('table').nth(0).locator('tbody tr').count(),12);
    assert.match(await host.innerText(),/2026-07-24/);
    assert.match(await host.innerText(),/不补造第三季度/);
    checks.push('twelve-port sources and unavailable third quarter are explicit');
    assert.equal(await host.locator('table').nth(1).locator('tbody tr').count(),11);
    assert.match(await host.innerText(),/dueling_imitation_only/);
    assert.match(await host.innerText(),/dueling_guided_ddqn/);
    assert.match(await host.innerText(),/没有MPC回退/);
    await host.locator('h3').filter({hasText:'RL与更强MPC'}).scrollIntoViewIfNeeded();
    await page.screenshot({path:path.join(out,'strong-mpc-and-rl.png')});
    checks.push('strong baselines, imitation snapshots, RL and unfavorable results are distinct');
    assert.equal(await host.locator('table').nth(2).locator('tbody tr').count(),12);
    assert.equal(await host.locator('table').nth(3).locator('tbody tr').count(),63);
    assert.match(await host.innerText(),/no_evaluable_observations/);
    assert.match(await host.innerText(),/4—6周/);
    await host.locator('h3').filter({hasText:'国际物理标定'}).scrollIntoViewIfNeeded();
    await page.screenshot({path:path.join(out,'international-twin-failures.png')});
    checks.push('all forecast and63 physical cells visible, including missing observations and archive latency');
    await host.locator('summary').filter({hasText:'48个同日工程场景'}).click();
    assert.equal(await host.locator('table').nth(4).locator('tbody tr').count(),48);
    assert.match(await host.locator('table').nth(4).innerText(),/暂缓/);
    checks.push('public-history operational scenarios preserve incomplete work, deficits and withheld UKC');
    await page.locator('[data-cp=history]').click();
    await page.locator('[data-cp=select][data-id="hc-1aba62a9c3d9490f86f64c86151d7eef"]').click();
    await page.locator('[data-cp-result] h3').filter({hasText:'已完成'}).waitFor();
    await page.locator('[data-cp=readiness]').click();
    const matrix=page.locator('[data-cp-readiness]');
    await matrix.locator('h3').waitFor();
    assert.match(await matrix.innerText(),/5 \/ 11/);
    assert.match(await matrix.innerText(),/完整验收未通过/);
    const quality=matrix.locator('tbody tr').filter({hasText:'当前全仓发布与代码质量'});
    assert.match(await quality.innerText(),/所列研究检查通过/);
    await matrix.locator('h3').scrollIntoViewIfNeeded();
    await page.screenshot({path:path.join(out,'current-five-of-eleven.png')});
    checks.push('current matrix updates to5/11 with release passed and field evidence still blocked');
    const pending=page.waitForEvent('download');
    await page.locator('[data-cp=export]').click();
    const filename=path.join(out,'ui-evidence.json');await(await pending).saveAs(filename);
    const data=JSON.parse(await fs.readFile(filename,'utf8'));
    assert.equal(data.remediation.current,true);
    assert.equal(data.remediation.crossport.excluded_test_windows.length,12);
    assert.equal(data.remediation.physical.long_passed,8);
    assert.equal(data.remediation.physical.short_passed,35);
    assert.equal(data.readiness.passed_items,5);
    assert.equal(data.readiness.production_authority,false);
    checks.push('actual browser export retains new sources, assumptions, failed cells and current release evidence');
    await page.setViewportSize({width:390,height:844});
    await host.locator('h3').first().scrollIntoViewIfNeeded();
    const widths=await host.evaluate(el=>({width:el.getBoundingClientRect().width,viewport:innerWidth}));
    assert.ok(widths.width<=widths.viewport);
    await page.screenshot({path:path.join(out,'mobile-new-evidence.png')});
    checks.push('new evidence workbench remains contained in a narrow viewport');
    assert.deepEqual(errors,[]);
    await fs.writeFile(path.join(out,'acceptance.json'),JSON.stringify({passed:true,checks,errors},null,2));
    console.log(JSON.stringify({passed:true,checks,errors}));
  }finally{await browser.close();}
})().catch(e=>{console.error(e);process.exit(1);});
