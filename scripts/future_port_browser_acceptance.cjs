const {chromium}=require("playwright");
const fs=require("node:fs/promises");
const path=require("node:path");
const assert=require("node:assert/strict");

(async()=>{
  const out=path.resolve(process.env.FUTURE_PORT_OUTPUT||".codex_artifacts/future-port-20261030/browser");
  await fs.mkdir(out,{recursive:true});
  const browser=await chromium.launch({headless:true,channel:"chrome"});
  const page=await browser.newPage({viewport:{width:1440,height:1050},acceptDownloads:true});
  const errors=[],checks=[];
  page.on("pageerror",e=>errors.push(e.message));
  try{
    await page.goto(process.env.FUTURE_PORT_URL||"http://127.0.0.1:8010",{waitUntil:"domcontentloaded"});
    await page.locator("#jointHarnessBtn").click();
    await page.locator('[data-jh="public-data"]').click();
    await page.locator('[data-jh-public-sources] h3').filter({hasText:"6个数据集"}).waitFor();
    assert.equal(await page.locator('[data-jh-public-sources] > details').count(),6);
    const first=page.locator('[data-jh-public-sources] > details').first();
    await first.locator(':scope > summary').click();
    assert.match(await first.innerText(),/m MLLW/);
    assert.match(await first.innerText(),/2024-12-23/);
    assert.match(await first.locator('a').first().getAttribute('href'),/^https:\/\//);
    checks.push("six source cards disclose provider, period, units, missingness, raw links and hashes");
    await page.locator('[data-jh="public-study"]').click();
    await page.locator('[data-jh-public-results] h3').filter({hasText:"los_angeles"}).waitFor();
    assert.equal(await page.locator('[data-jh-public-results] tbody tr').count(),3);
    assert.match(await page.locator('[data-jh-public-results]').innerText(),/工程场景计算结果/);
    await page.locator('[data-jh-public-results]').screenshot({path:path.join(out,"los-angeles-jit.png")});
    checks.push("real historical LA study compares three complete resource schedules");
    await page.locator('[name=publicSite]').selectOption("singapore");
    await page.locator('[name=publicScenario]').selectOption("resource_outage");
    await page.locator('[data-jh="public-study"]').click();
    await page.locator('[data-jh-public-results] h3').filter({hasText:"singapore"}).waitFor();
    assert.match(await page.locator('[data-jh-public-results]').innerText(),/单位尺度/);
    checks.push("Singapore study preserves unresolved absolute unit scale and explicit outages");
    await page.locator('[name=publicScenario]').selectOption("observed_high_wind");
    await page.locator('[data-jh="public-study"]').click();
    await page.locator('[data-jh-notice]').filter({hasText:"不得移用"}).waitFor();
    assert.equal(await page.locator('[data-jh-public-results] h3').filter({hasText:"singapore"}).count(),0);
    checks.push("unsupported cross-port weather fails visibly and clears old study");
    await page.locator('[data-jh="public-forecast"]').click();
    await page.locator('[data-jh-public-results] h3').filter({hasText:"NOAA水位"}).waitFor();
    assert.match(await page.locator('[data-jh-public-results]').innerText(),/672/);
    await page.locator('[data-jh-public-results]').screenshot({path:path.join(out,"water-level-holdout.png")});
    checks.push("real frozen NOAA forecast validation renders holdout error and persistence comparator");
    assert.equal(await page.locator('[data-jh-notice]').getAttribute('data-error'),"false");
    await page.locator('[data-jh="research-history"]').click();
    await page.locator('[data-jh="select-study"]').first().waitFor();
    await page.locator('[data-jh="select-study"]').first().click();
    await page.locator('[data-jh-study] th').filter({hasText:"配对差值95% t区间"}).waitFor();
    assert.match(await page.locator('[data-jh-study]').innerText(),/基线对照/);
    await page.locator('[data-jh-study]').screenshot({path:path.join(out,"research-intervals.png")});
    checks.push("actual research history renders paired intervals, baseline labels and admission blockers");
    const download=page.waitForEvent("download");
    await page.locator('[data-jh="public-export"]').click();
    await (await download).saveAs(path.join(out,"ui-public-evidence.json"));
    const receipt=JSON.parse(await fs.readFile(path.join(out,"ui-public-evidence.json"),"utf8"));
    assert.equal(receipt.public_data.entries.length,6);
    assert.equal(receipt.forecast.operational_release,false);
    checks.push("actual browser export retains sources and disabled physical release");
    await page.setViewportSize({width:390,height:844});
    await page.locator('[data-jh="public-forecast"]').scrollIntoViewIfNeeded();
    await page.screenshot({path:path.join(out,"mobile-public-panel.png")});
    const width=await page.locator('.hx-public-lab').first().evaluate(el=>({width:el.getBoundingClientRect().width,viewport:innerWidth}));
    assert.ok(width.width<=width.viewport);
    checks.push("public study panel fits narrow viewport and retains scrollable tables");
    assert.deepEqual(errors,[]);
    await fs.writeFile(path.join(out,"acceptance.json"),JSON.stringify({passed:true,checks,errors},null,2));
    console.log(JSON.stringify({passed:true,checks,errors}));
  }finally{await browser.close();}
})().catch(e=>{console.error(e);process.exit(1);});
